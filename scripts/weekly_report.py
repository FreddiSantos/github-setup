"""Relatórios de rotina sobre todos os repositórios públicos do dono, publicados como issues.

Modos:
  summary   cria a issue "Weekly summary — AAAA-Www" com a atividade dos últimos 7 dias
            e fecha os resumos anteriores.
  reminder  mantém uma única issue "PRs waiting for review" com os PRs abertos há mais de
            N dias; comenta mencionando o dono quando há PRs e fecha a issue quando não há.

Uso: python scripts/weekly_report.py summary|reminder
Env: GITHUB_TOKEN (obrigatória), GITHUB_REPOSITORY (onde criar as issues, ex.: dono/github-setup),
     REMINDER_DAYS (padrão 3). Só usa a biblioteca padrão.
"""

from __future__ import annotations

import json
import os
import sys
import urllib.parse
import urllib.request
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta

API = "https://api.github.com"
LABEL = "report"
SUMMARY_PREFIX = "📊 Weekly summary"
REMINDER_TITLE = "🔔 PRs waiting for review"


# ---------- acesso à API ----------


class GitHub:
    def __init__(self, token: str) -> None:
        self.token = token

    def request(self, method: str, path: str, body: dict | None = None) -> dict | list:
        url = path if path.startswith("http") else f"{API}{path}"
        data = json.dumps(body).encode() if body is not None else None
        req = urllib.request.Request(
            url,
            data=data,
            method=method,
            headers={
                "Authorization": f"Bearer {self.token}",
                "Accept": "application/vnd.github+json",
                "X-GitHub-Api-Version": "2022-11-28",
                "Content-Type": "application/json",
            },
        )
        with urllib.request.urlopen(req, timeout=30) as resp:
            raw = resp.read()
        return json.loads(raw) if raw else {}

    def get(self, path: str, **params: str | int) -> list:
        query = f"?{urllib.parse.urlencode(params)}" if params else ""
        result = self.request("GET", f"{path}{query}")
        return result if isinstance(result, list) else [result]

    def search_count(self, q: str) -> int:
        result = self.request("GET", f"/search/issues?{urllib.parse.urlencode({'q': q})}")
        assert isinstance(result, dict)
        return int(result["total_count"])


# ---------- modelo e formatação (funções puras, testáveis) ----------


@dataclass(frozen=True)
class RepoActivity:
    name: str
    commits: int
    prs_opened: int
    prs_merged: int
    issues_opened: int
    issues_closed: int
    releases: list[str]

    @property
    def is_empty(self) -> bool:
        return not (
            self.commits
            or self.prs_opened
            or self.prs_merged
            or self.issues_opened
            or self.issues_closed
            or self.releases
        )


@dataclass(frozen=True)
class OpenPR:
    repo: str
    number: int
    title: str
    url: str
    author: str
    created_at: datetime

    def age_days(self, now: datetime) -> int:
        return (now - self.created_at).days


def iso_week(now: datetime) -> str:
    year, week, _ = now.isocalendar()
    return f"{year}-W{week:02d}"


def render_summary(activity: list[RepoActivity], open_prs: list[OpenPR], now: datetime) -> str:
    active = [a for a in activity if not a.is_empty]
    since = (now - timedelta(days=7)).strftime("%Y-%m-%d")
    lines = [f"Activity from **{since}** to **{now:%Y-%m-%d}** across public repositories.", ""]

    if active:
        lines += [
            "| Repository | Commits | PRs opened | PRs merged | Issues opened | Issues closed |"
            " Releases |",
            "|---|---:|---:|---:|---:|---:|---|",
        ]
        for a in sorted(active, key=lambda a: a.commits, reverse=True):
            releases = ", ".join(a.releases) or "—"
            lines.append(
                f"| {a.name} | {a.commits} | {a.prs_opened} | {a.prs_merged} | "
                f"{a.issues_opened} | {a.issues_closed} | {releases} |"
            )
        total = sum(a.commits for a in active)
        lines += ["", f"**Total commits:** {total}"]
    else:
        lines.append("_No activity this week._")

    lines += ["", "### Open pull requests", ""]
    if open_prs:
        for pr in sorted(open_prs, key=lambda p: p.created_at):
            lines.append(
                f"- [{pr.repo}#{pr.number}]({pr.url}) {pr.title} "
                f"(by {pr.author}, {pr.age_days(now)} days old)"
            )
    else:
        lines.append("_None._ 🎉")

    lines += ["", "<sub>Generated by github-setup/.github/workflows/weekly-summary.yml</sub>"]
    return "\n".join(lines)


def stale_prs(open_prs: list[OpenPR], now: datetime, min_days: int) -> list[OpenPR]:
    return sorted((p for p in open_prs if p.age_days(now) >= min_days), key=lambda p: p.created_at)


def render_reminder(prs: list[OpenPR], now: datetime, min_days: int) -> str:
    lines = [f"Pull requests open for **{min_days}+ days** (updated {now:%Y-%m-%d}):", ""]
    lines += [
        f"- [ ] [{p.repo}#{p.number}]({p.url}) {p.title} — {p.age_days(now)} days, by {p.author}"
        for p in prs
    ]
    lines += [
        "",
        "This issue closes itself when there are no old PRs left.",
        "",
        "<sub>Generated by github-setup/.github/workflows/pr-reminder.yml</sub>",
    ]
    return "\n".join(lines)


# ---------- coleta ----------


def list_repos(gh: GitHub, owner: str) -> list[dict]:
    repos = gh.get(f"/users/{owner}/repos", per_page=100, type="owner")
    return [r for r in repos if not (r["fork"] or r["archived"] or r["private"])]


def collect_open_prs(gh: GitHub, repos: list[dict]) -> list[OpenPR]:
    prs = []
    for repo in repos:
        for pr in gh.get(f"/repos/{repo['full_name']}/pulls", state="open", per_page=100):
            if pr["draft"]:
                continue
            prs.append(
                OpenPR(
                    repo=repo["name"],
                    number=pr["number"],
                    title=pr["title"],
                    url=pr["html_url"],
                    author=pr["user"]["login"],
                    created_at=datetime.fromisoformat(pr["created_at"].replace("Z", "+00:00")),
                )
            )
    return prs


def collect_activity(gh: GitHub, repos: list[dict], now: datetime) -> list[RepoActivity]:
    since = now - timedelta(days=7)
    since_iso = since.strftime("%Y-%m-%dT%H:%M:%SZ")
    day = since.strftime("%Y-%m-%d")
    out = []
    for repo in repos:
        full = repo["full_name"]
        commits = gh.get(f"/repos/{full}/commits", since=since_iso, per_page=100)
        releases = [
            r["tag_name"]
            for r in gh.get(f"/repos/{full}/releases", per_page=20)
            if r.get("published_at") and r["published_at"] >= since_iso
        ]
        out.append(
            RepoActivity(
                name=repo["name"],
                commits=len(commits),
                prs_opened=gh.search_count(f"repo:{full} is:pr created:>={day}"),
                prs_merged=gh.search_count(f"repo:{full} is:pr is:merged merged:>={day}"),
                issues_opened=gh.search_count(f"repo:{full} is:issue created:>={day}"),
                issues_closed=gh.search_count(f"repo:{full} is:issue is:closed closed:>={day}"),
                releases=releases,
            )
        )
    return out


# ---------- publicação ----------


def open_report_issues(gh: GitHub, target: str) -> list[dict]:
    issues = gh.get(f"/repos/{target}/issues", state="open", labels=LABEL, per_page=100)
    return [i for i in issues if "pull_request" not in i]


def run_summary(gh: GitHub, owner: str, target: str, now: datetime) -> None:
    repos = list_repos(gh, owner)
    body = render_summary(collect_activity(gh, repos, now), collect_open_prs(gh, repos), now)
    title = f"{SUMMARY_PREFIX} — {iso_week(now)}"

    existing = [i for i in open_report_issues(gh, target) if i["title"].startswith(SUMMARY_PREFIX)]
    current = next((i for i in existing if i["title"] == title), None)
    if current:
        gh.request("PATCH", f"/repos/{target}/issues/{current['number']}", {"body": body})
        print(f"Updated #{current['number']}")
    else:
        issue = gh.request(
            "POST", f"/repos/{target}/issues", {"title": title, "body": body, "labels": [LABEL]}
        )
        assert isinstance(issue, dict)
        print(f"Created #{issue['number']}")
    for old in existing:
        if old["title"] != title:
            gh.request(
                "PATCH",
                f"/repos/{target}/issues/{old['number']}",
                {"state": "closed", "state_reason": "completed"},
            )
            print(f"Closed old summary #{old['number']}")


def run_reminder(gh: GitHub, owner: str, target: str, now: datetime, min_days: int) -> None:
    prs = stale_prs(collect_open_prs(gh, list_repos(gh, owner)), now, min_days)
    issue = next((i for i in open_report_issues(gh, target) if i["title"] == REMINDER_TITLE), None)

    if not prs:
        if issue:
            gh.request(
                "PATCH",
                f"/repos/{target}/issues/{issue['number']}",
                {"state": "closed", "state_reason": "completed"},
            )
            print(f"No old PRs; closed #{issue['number']}")
        else:
            print("No old PRs.")
        return

    body = render_reminder(prs, now, min_days)
    if issue:
        gh.request("PATCH", f"/repos/{target}/issues/{issue['number']}", {"body": body})
        number = issue["number"]
    else:
        created = gh.request(
            "POST",
            f"/repos/{target}/issues",
            {"title": REMINDER_TITLE, "body": body, "labels": [LABEL]},
        )
        assert isinstance(created, dict)
        number = created["number"]
    gh.request(
        "POST",
        f"/repos/{target}/issues/{number}/comments",
        {"body": f"@{owner} {len(prs)} pull request(s) have been waiting {min_days}+ days."},
    )
    print(f"Reminder on #{number}: {len(prs)} PR(s)")


def main(argv: list[str]) -> int:
    if not argv or argv[0] not in {"summary", "reminder"}:
        print(__doc__, file=sys.stderr)
        return 2
    target = os.environ["GITHUB_REPOSITORY"]
    owner = target.split("/")[0]
    gh = GitHub(os.environ["GITHUB_TOKEN"])
    now = datetime.now(UTC)
    if argv[0] == "summary":
        run_summary(gh, owner, target, now)
    else:
        run_reminder(gh, owner, target, now, int(os.environ.get("REMINDER_DAYS", "3")))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
